// штука с массивом
#include <iostream>
#include <clocale>
using namespace std;

int main() 
{
    setlocale(LC_ALL, ".65001");

    int n;
    cout << "Введите размер массива: ";
    cin >> n;

    if (n <= 0) 
    {
        cout << "Размер должен быть положительным числом." << endl;
        return 1;
    }

    // 1. Создаем динамический массив
    int* arr = new int[n];

    cout << "Введите " << n << " элементов массива:" << endl;
    for (int i = 0; i < n; ++i) 
    {
        cin >> *(arr + i); // Арифметика указателей: arr[i] == *(arr + i)
    }

    // Обработка массива с использованием арифметики указателей
    // Проходим по всем элементам через указатель ptr, который двигается по массиву
    for (int* ptr = arr; ptr < arr + n; ++ptr) 
    {
        int index = ptr - arr; // Вычисляем индекс через разность указателей

        if (index == 0 || index == n - 1) 
        {
            // Первый или последний элемент -> заменяем на 0
            *ptr = 0;
        } 
        else if (*ptr % 2 == 0) 
        {
            // Четный элемент: заменяем на сумму предыдущего и следующего
            // Используем арифметику указателей для доступа к соседям
            int prevVal = *(ptr - 1);
            int nextVal = *(ptr + 1);
            *ptr = prevVal + nextVal;
        }
        // Если элемент нечетный и не граничный — ничего не делаем
    }

    // 4. Выводим массив на экран
    cout << "\nРезультат:" << endl;
    for (int i = 0; i < n; ++i) 
    {
        cout << *(arr + i) << " "; // Арифметика указателей при выводе
    }
    cout << endl;

    // 5. Освобождаем выделенную память
    delete[] arr;
    arr = nullptr; // Хорошая практика: обнулить указатель после удаления

    return 0;
}
